/**
 * One anchor point per country/territory, for great-circle trade-flow arcs
 * (`src/components/layers/TradeFlowsLayer.tsx`). An arc needs a single point
 * per side; a country's Natural Earth centroid is frequently the wrong one
 * for *energy* trade, and BACI carries codes for entrepôts and territories
 * that have no polygon in the 1:110m file at all (Singapore, Bahrain, Malta,
 * Hong Kong, …).
 *
 * Coverage: every code in `NATURAL_EARTH_ISO3`
 * (`src/lib/geo/iso3.ts`) plus every code in `EXTRA_COUNTRY_NAMES`
 * (`src/lib/geo/countries.ts`) — the same two lists a `focus` selection and
 * the country name lookup already rely on. `trade_flow.parquet`'s 229
 * distinct exporter/importer codes (1995–2024) are a subset of that union
 * with none left over (checked against the shipped parquet on 2026-09-19),
 * so every pair the layer can draw resolves.
 *
 * Base points: the *representative point* (guaranteed inside the polygon,
 * unlike a raw centroid) of a country's **largest** sub-polygon in
 * `countries.geojson` — largest, so an archipelago or a country with distant
 * overseas territories isn't dragged toward open ocean or averaged toward a
 * point outside every landmass.
 *
 * Hand overrides (representative point too misleading for *energy* trade
 * specifically):
 *  - USA → US Gulf Coast (Houston/Corpus Christi): most crude + LNG exports
 *    load there, not from the geographic centre of the Great Plains.
 *  - RUS → western Russia (Moscow/Ust-Luga/Novorossiysk corridor): oil and
 *    gas move west to Europe or south via the Black Sea; the raw centroid
 *    sits deep in Siberia, nowhere near an export route.
 *  - CAN → Alberta oil sands (Edmonton): the crude export origin.
 *  - AUS → NW Shelf, Western Australia (Karratha/Gorgon): the LNG export
 *    hub; the geographic centroid is empty desert.
 *  - NOR → Stavanger / North Sea: the oil + gas hub, not central Norway.
 *  - CHL → Valparaíso: a representative point of a long thin country can
 *    land far from any port that ships anything.
 *  - IDN → Bontang, East Kalimantan: an LNG export hub; Indonesia's
 *    population (and a naive centroid) skews toward Java.
 *  - MYS → Bintulu, Sarawak: the LNG export hub; the peninsula skews a
 *    naive centroid west of the LNG-exporting East Malaysian states.
 *  - FRA → Paris/mainland: French Guiana, Réunion and other overseas
 *    territories are separate polygons in the same feature and would skew a
 *    plain (non-largest-polygon) centroid; explicit here so the choice reads
 *    as deliberate rather than accidental.
 *
 * Territory anchors (no Natural Earth polygon) are each territory's capital
 * or largest settlement — plausible without being load-bearing for any
 * specific route, since none of these carry the top-N pairs (only Singapore,
 * Bahrain, Hong Kong and Malta appear in a top-150 pair, per
 * `tests/unit/geo/country-anchors.test.ts`).
 */

